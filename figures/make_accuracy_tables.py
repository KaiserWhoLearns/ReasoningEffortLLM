#!/usr/bin/env python3
"""Accuracy tables with their uncertainty, written to output/tables/.

- `app_perf.tex`: overall accuracy per model and effort with a 95% interval. On the agentic
  benchmarks the rate is k of n tasks solved and the interval is Wilson's (`stats.wilson`). On
  AIME and GPQA the rate is the mean per-attempt correctness and the interval is a percentile
  bootstrap over problems (`stats.boot_ci` on per-problem rates), since attempts on one problem
  are not independent.
- `swebenchpro_corrected_perf.tex`: original vs. corrected SWE-Bench Pro at each model's highest
  common effort, with an exact McNemar test on the paired 44 pilot instances, Holm-adjusted
  across models, and a sign test across models (printed).

Reads recorded runs only; no API calls.

    python figures/make_accuracy_tables.py
"""
from __future__ import annotations

import argparse
import sys
from collections import defaultdict
from pathlib import Path

from scipy.stats import binomtest

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import datasets  # noqa: E402
import style  # noqa: E402
from common import paths  # noqa: E402
from stats import boot_ci  # noqa: E402

TABLES = paths.output_dir("tables")
EFFORTS = ["none", "low", "medium", "high", "xhigh", "max"]


def per_problem_rates(benchmark: str, module_dir: str, module_name: str, idx_key: str):
    """{(model, effort): [per-problem mean correctness]} read from the stored samples."""
    mod = datasets._import_benchmark(module_dir, module_name)
    data_root = paths.data_root(benchmark)
    out = {}
    for model in style.MODELS:
        for effort in EFFORTS:
            samples = mod.read_samples(mod.run_dir(data_root, model, effort) / mod.SAMPLES_FILE)
            if not samples:
                continue
            correct = defaultdict(list)
            for s in samples:
                correct[s[idx_key]].append(bool(s["correct"]))
            if len(correct) < datasets.MIN_UNITS:
                continue
            out[(model, effort)] = [sum(v) / len(v) for v in correct.values()]
    return out


def rate_cells(rates_by_run):
    cells = {}
    for key, rates in rates_by_run.items():
        mean, lo, hi = boot_ci(rates)
        cells[key] = (100 * mean, 100 * lo, 100 * hi)
    return cells


def run_cells(runs):
    return {(r.model, r.effort): r.accuracy for r in runs}


def fmt_cell(cell, best):
    pct, lo, hi = cell
    value = f"{pct:.1f}"
    if best:
        value = f"\\textbf{{{value}}}"
    return f"{value}\\,{{\\scriptsize[{lo:.0f}, {hi:.0f}]}}"


def block(title, cells):
    lines = [f"        \\multicolumn{{7}}{{@{{}}l}}{{\\textbf{{{title}}}}} \\\\",
             "        \\addlinespace[2pt]"]
    for model in style.MODELS:
        row = {e: cells[(model, e)] for e in EFFORTS if (model, e) in cells}
        if not row:
            continue
        top = round(max(c[0] for c in row.values()), 1)
        parts = [fmt_cell(row[e], round(row[e][0], 1) == top) if e in row else "--"
                 for e in EFFORTS]
        lines.append(f"        {style.label_of(model)} & " + " & ".join(parts) + " \\\\")
    return lines


def write_app_perf(aime, gpqa, tb, pro, pro_corr):
    header = [
        "% Generated by figures/make_accuracy_tables.py.",
        "% Full benchmark cohorts; SWE-Bench Pro restricted with datasets._pilot_ids().",
        "\\begin{table}[p]",
        "    \\centering",
        "    \\small",
        "    \\setlength{\\tabcolsep}{3pt}",
        "    \\caption{Overall accuracy (\\%) across reasoning-effort settings, with 95\\% "
        "confidence intervals in brackets, rounded to whole percentage points.",
        "    AIME and GPQA report mean per-attempt correctness, with percentile bootstrap "
        "intervals (10,000 resamples) over problems that keep each problem's attempts together; "
        "the agentic benchmarks report the fraction of tasks solved, with Wilson score intervals.",
        "    Intervals describe each setting separately; because all settings of a model share "
        "the same tasks, paired tests between settings are more sensitive than a comparison of "
        "overlapping intervals.",
        "    Bold marks the highest accuracy within each model--benchmark row, including ties; "
        "dashes indicate settings without a reported result.",
        "    Effort names retain their model-specific meanings.}",
        "    \\label{tab:app_perf}",
        "    \\begin{tabular}{@{}lrrrrrr@{}}",
        "        \\toprule",
        "        Model & \\texttt{none} & \\texttt{low} & \\texttt{medium} & \\texttt{high} "
        "& \\texttt{xhigh} & \\texttt{max} \\\\",
        "        \\midrule",
    ]
    body = []
    blocks = [
        ("AIME 2026 (30 problems; 10 attempts per problem)", aime),
        ("GPQA Diamond (198 questions; 4 attempts per question)", gpqa),
        ("Terminal-Bench 2.1 (89 tasks)", tb),
        ("SWE-Bench Pro, original (44 instances)", pro),
        ("SWE-Bench Pro, corrected (44 instances)", pro_corr),
    ]
    for i, (title, cells) in enumerate(blocks):
        if i:
            body.append("        \\midrule")
        body.extend(block(title, cells))
    footer = [
        "        \\bottomrule",
        "    \\end{tabular}",
        "\\end{table}",
    ]
    write(TABLES / "app_perf.tex", header + body + footer)


def write(path, lines):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n")
    print(f"wrote {path}")


def holm(pvalues):
    order = sorted(range(len(pvalues)), key=pvalues.__getitem__)
    adjusted, running = [0.0] * len(pvalues), 0.0
    for rank, i in enumerate(order):
        running = max(running, min(1.0, (len(pvalues) - rank) * pvalues[i]))
        adjusted[i] = running
    return adjusted


def fmt_p(p):
    if p < 0.001:
        return "$<$0.001"
    return f"{p:.3f}"


def write_corrected(pro_runs, corr_runs, pilot):
    orig = {(r.model, r.effort): r for r in pro_runs}
    corr = {(r.model, r.effort): r for r in corr_runs}
    rows = []
    for model in style.MODELS:
        common = [e for e in EFFORTS if (model, e) in orig and (model, e) in corr]
        if not common:
            continue
        effort = common[-1]
        o, c = orig[(model, effort)], corr[(model, effort)]
        assert o.n_units == c.n_units == len(pilot), (model, o.n_units, c.n_units)
        only_orig = len(o.resolved_units - c.resolved_units)
        only_corr = len(c.resolved_units - o.resolved_units)
        p = binomtest(only_orig, only_orig + only_corr, 0.5).pvalue if only_orig + only_corr else 1.0
        rows.append(dict(model=model, effort=effort, o=100 * o.n_resolved / o.n_units,
                         c=100 * c.n_resolved / c.n_units, only_orig=only_orig,
                         only_corr=only_corr, p=p))
    for row, adj in zip(rows, holm([r["p"] for r in rows])):
        row["p_holm"] = adj
    n_down = sum(r["c"] < r["o"] for r in rows)
    sign_p = binomtest(n_down, len(rows), 0.5).pvalue
    for r in rows:
        print(f"{style.label_of(r['model']):18s} {r['effort']:6s} {r['o']:5.1f} -> {r['c']:5.1f}"
              f"  orig-only {r['only_orig']:2d}  corr-only {r['only_corr']:2d}"
              f"  p={r['p']:.4f}  holm={r['p_holm']:.4f}")
    print(f"sign test across models: {n_down}/{len(rows)} lower, p={sign_p:.4f}")

    n_sig = sum(r["p"] < 0.05 for r in rows)
    n_sig_holm = sum(r["p_holm"] < 0.05 for r in rows)
    print(f"significant at 0.05: {n_sig} of {len(rows)} ({n_sig_holm} after Holm correction)")

    lines = [
        "% Generated by figures/make_accuracy_tables.py.",
        "% Highest common reasoning-effort setting for each model; default source cost cap "
        "retained.",
        "\\begin{table}[t]",
        "    \\centering",
        "    \\small",
        "    \\setlength{\\tabcolsep}{5pt}",
        "    \\caption{Solve rates on the original and corrected SWE-Bench Pro environments at "
        "each model's highest evaluated reasoning-effort setting, using the same 44 instances in "
        "both environments.",
        "    Corrected removes the task repository's original git history and restricts network "
        "access to allowlisted package registries.",
        "    $\\Delta$ is corrected minus original solve rate in percentage points, computed "
        "before rounding.",
        "    The \\emph{Solved only in} columns count discordant instances, and $p$ is the "
        "two-sided exact McNemar test on those counts.",
        f"    The decrease is significant at $\\alpha = 0.05$ for {n_sig} of {len(rows)} models, "
        f"and a sign test over the {len(rows)} models, all of which decrease, gives "
        f"$p = {sign_p:.3f}$.",
        "    Both conditions follow the source scoring rule that evaluator-passed executions "
        "costing more than \\$5 count as failures.",
        "    Table~\\ref{tab:app_perf} reports results at all effort levels.}",
        "    \\label{tab:swebenchpro-corrected-perf}",
        "    \\begin{tabular}{@{}llrrrrrr@{}}",
        "        \\toprule",
        "        & & & & & \\multicolumn{2}{c}{Solved only in} & \\\\",
        "        \\cmidrule(lr){6-7}",
        "        Model & Effort & Original (\\%) & Corrected (\\%) & $\\Delta$ (pp) "
        "& Original & Corrected & $p$ \\\\",
        "        \\midrule",
    ]
    for r in rows:
        lines.append(
            f"        {style.label_of(r['model'])} & \\texttt{{{r['effort']}}} & {r['o']:.1f} & "
            f"{r['c']:.1f} & ${r['c'] - r['o']:+.1f}$ & {r['only_orig']} & {r['only_corr']} & "
            f"{fmt_p(r['p'])} \\\\")
    lines += [
        "        \\bottomrule",
        "    \\end{tabular}",
        "\\end{table}",
    ]
    write(TABLES / "swebenchpro_corrected_perf.tex", lines)


def main():
    argparse.ArgumentParser(description=__doc__,
                            formatter_class=argparse.RawDescriptionHelpFormatter).parse_args()
    pilot = datasets._pilot_ids()
    pro_runs, _ = datasets.load_pro("swebench-pro", subset=pilot)
    corr_runs, _ = datasets.load_pro("swebench-pro-corrected", subset=pilot)
    tb_runs, _ = datasets.load_tb()
    aime = rate_cells(per_problem_rates("aime-2026", "aime_2026", "aime", "problem_idx"))
    gpqa = rate_cells(per_problem_rates("gpqa-diamond", "gpqa_diamond", "gpqa", "question_idx"))
    write_app_perf(aime, gpqa, run_cells(tb_runs), run_cells(pro_runs), run_cells(corr_runs))
    write_corrected(pro_runs, corr_runs, pilot)


if __name__ == "__main__":
    main()
